"""Help Desk Queue tickets for Security.

The queue UI lives on the learner-features branch and is not merged here.
Each record is the same shape as learner.tickets.hd so a later import can append
TICKETS to that list. Nothing here calls a network service.
"""

PRIORITIES = ('low', 'medium', 'high', 'critical')


def hd(tid, title, caller, priority, opening, qa, steps, required, keywords, lab=None, area='Security'):
    tree = {'start': {'reply': '', 'asks': []}}
    for qid, ask, reply, fqid, fask, freply in qa:
        tree['start']['asks'].append({'id': qid, 'text': ask, 'next': qid})
        follow = []
        if fqid:
            follow.append({'id': fqid, 'text': fask, 'next': fqid})
            tree[fqid] = {'reply': freply, 'asks': []}
        tree[qid] = {'reply': reply, 'asks': follow}
    return {
        'id': tid, 'course': 'SEC', 'title': title, 'caller': caller, 'priority': priority,
        'opening': opening, 'tree': tree, 'area': area,
        'steps': [{'id': a, 'text': b, 'good': c} for a, b, c in steps],
        'required': list(required), 'keywords': list(keywords),
        'lab_id': lab, 'target_sec': 480,
    }


