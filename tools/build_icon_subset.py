"""Build the Bootstrap Icons subset the app actually uses.

The full icon font is ~130 KB (woff2) plus ~86 KB of CSS for ~2,000 icons; the app uses about a hundred.
This scans templates, JS and Python for `bi-<name>` classes (plus bare names passed to the
`empty_state()` macro), keeps the ones Bootstrap Icons defines, and writes:
  static/vendor/bootstrap-icons/1.11.3/bootstrap-icons-subset.css
  static/vendor/bootstrap-icons/1.11.3/fonts/bootstrap-icons-subset-<hash>.woff2
The font name carries a content hash, so its immutable cache entry can never go stale.
Re-run after adding a new icon (tests/test_ux.py fails if an icon is missing from the subset):
  ./venv/bin/python tools/build_icon_subset.py        (needs fonttools; see requirements-dev.txt)
"""
import hashlib, pathlib, re, sys
from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parents[1]
ICONS = ROOT / 'static/vendor/bootstrap-icons/1.11.3'
FULL_CSS, FULL_FONT = ICONS / 'bootstrap-icons.min.css', ICONS / 'fonts/bootstrap-icons.woff2'
OUT_CSS = ICONS / 'bootstrap-icons-subset.css'
SKIP = re.compile(r'\(\d\)|/vendor/|/archive/|/venv/|/node_modules/|__pycache__')


def used_icons():
    names = set()
    files = [p for g in ('templates/**/*.html', 'static/js/**/*.js', '*.py', 'helix/**/*.py') for p in ROOT.glob(g)]
    for p in files:
        if SKIP.search(str(p)):
            continue
        t = p.read_text(errors='ignore')
        names |= set(re.findall(r'\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)', t))
        names |= set(re.findall(r"empty_state\(\s*'([a-z0-9-]+)'", t))
    return names


def main():
    css = FULL_CSS.read_text()
    defined = dict(re.findall(r'\.bi-([a-z0-9-]+)::before\{content:"\\([0-9a-f]+)"\}', css))
    used = sorted(n for n in used_icons() if n in defined)
    codepoints = [int(defined[n], 16) for n in used]
    opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = []; opts.name_IDs = ['*']; opts.notdef_outline = True
    font = subset.load_font(str(FULL_FONT), opts)
    s = subset.Subsetter(opts); s.populate(unicodes=codepoints); s.subset(font)
    tmp = ICONS / 'fonts/_subset.woff2'
    subset.save_font(font, str(tmp), opts)
    h = hashlib.sha256(tmp.read_bytes()).hexdigest()[:10]
    for old in (ICONS / 'fonts').glob('bootstrap-icons-subset-*.woff2'):
        old.unlink()
    font_name = f'bootstrap-icons-subset-{h}.woff2'
    tmp.rename(ICONS / 'fonts' / font_name)
    base = re.search(r'\.bi::before,\[class\*=" bi-"\]::before,\[class\^=bi-\]::before\{[^}]*\}', css).group(0)
    rules = ''.join(f'.bi-{n}::before{{content:"\\{defined[n]}"}}' for n in used)
    OUT_CSS.write_text(
        '/*! Bootstrap Icons v1.11.3 (MIT, https://icons.getbootstrap.com/), subset of %d icons used by this app.\n'
        ' * Generated by tools/build_icon_subset.py; do not edit by hand. */\n'
        '@font-face{font-display:block;font-family:bootstrap-icons;src:url("fonts/%s") format("woff2")}\n%s\n%s\n'
        % (len(used), font_name, base, rules))
    print(f'{len(used)} icons -> {font_name} ({(ICONS / "fonts" / font_name).stat().st_size} B), CSS {OUT_CSS.stat().st_size} B')
    missing = sorted(used_icons() - set(defined))
    if missing:
        print('not Bootstrap Icons names (ignored):', ' '.join(missing))


if __name__ == '__main__':
    sys.exit(main())
