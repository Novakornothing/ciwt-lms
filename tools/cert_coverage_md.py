"""Write CERT_COVERAGE.md from curriculum_v2/cert/alignment.json and coverage_baseline.json (pass 11).

usage: python tools/cert_coverage_md.py [--check]
Run tools/cert_coverage.py first so alignment.json is current. --check exits 1 if CERT_COVERAGE.md is stale.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from curriculum_v2.cert.exams import DISCLAIMER, DOMAINS, EXAMS, OBJECTIVES, label, sort_key  # noqa: E402
from curriculum_v2.cert.mapping import CONTENT_COVERED, CONTENT_PARTIAL, ITEMS_COVERED  # noqa: E402
from curriculum_v2.cert.supplements import SUPPLEMENTS, GLOSSARY  # noqa: E402
from curriculum_v2.cert.items import CERT_ITEMS  # noqa: E402
from curriculum_v2.cert.authoring import SOURCES  # noqa: E402

CERT = os.path.join(ROOT, 'curriculum_v2', 'cert')


def build():
    a = json.load(open(os.path.join(CERT, 'alignment.json'), encoding='utf-8'))
    b = json.load(open(os.path.join(CERT, 'coverage_baseline.json'), encoding='utf-8'))
    objs, before = a['objectives'], b['status']
    L = ['# Certification coverage', '',
         f'_{DISCLAIMER}_', '',
         'Generated by `tools/cert_coverage_md.py` from `curriculum_v2/cert/alignment.json`; regenerate after content changes '
         '(`python tools/cert_coverage.py && python tools/cert_coverage_md.py`). The same data drives the staff page '
         '**Certification coverage** (`/staff/cert-coverage`).', '',
         '## Objectives documents', '']
    for e in EXAMS.values():
        L.append(f"- **{e['name']} {e['code']} ({e['version']})**: {e['doc_version']}. Document: <{e['url']}> "
                 f"(linked from <{e['page']}>). SHA-256 of the file used: `{e['sha256']}`. "
                 f"Official format stated in the document: {e['official']['questions'].lower()} questions, "
                 f"{e['official']['minutes']} minutes, passing score {e['official']['passing']}.")
    L += ['', '## How status is decided', '',
          f'- **Content**: each exam objective has a short checklist of the terms its bullet list names. The share of those terms found in the '
          f'linked CIWT lessons and labs is the *topic ratio*: covered at ≥ {CONTENT_COVERED:.0%}, partial at ≥ {CONTENT_PARTIAL:.0%}, otherwise a gap. '
          'A lesson is linked when it sits in a chapter the curated map assigns to the objective and mentions its terms, or mentions many of them anywhere.',
          f'- **Items**: covered with ≥ {ITEMS_COVERED} aligned bank items, partial with 1–{ITEMS_COVERED - 1}.',
          '- **Overall**: covered only when content and items are both covered; a gap when content is a gap; otherwise partial.',
          '- This is a keyword heuristic, not a judgement of depth or accuracy. Every pass-11 addition is tagged *Pending SME review*.',
          '- CompTIA publishes weights only per domain. The per-objective weights below divide each domain weight equally across its '
          'objectives; that is an assumption, used only to rank the work.', '',
          '## Before and after', '',
          '| Exam | Covered (before → after) | Partial | Gap | Weighted covered | Aligned items | Topic ratio |',
          '|---|---|---|---|---|---|---|']
    for k, e in EXAMS.items():
        s, o = a['summary'][k], b['summary'][k]
        L.append(f"| {e['short']} {e['code']} | {o['covered']} → **{s['covered']}** of {s['total']} | {o['partial']} → {s['partial']} | "
                 f"{o['gap']} → {s['gap']} | {o['weighted_covered']}% → **{s['weighted_covered']}%** | {o['items']} → {s['items']} | "
                 f"{o['topic_ratio']} → {s['topic_ratio']} |")
    gaps_before = sorted((k for k, v in before.items() if v == 'gap'), key=sort_key)
    L += ['', f"Gaps at the baseline ({len(gaps_before)}): " + ', '.join(f"{label(k)} ({OBJECTIVES[k]['title'].rstrip('.')})" for k in gaps_before) + '.',
          '', '## What pass 11 added', '',
          f'- **{len(SUPPLEMENTS)} lesson sections** appended to existing lessons (no lessons removed or rewritten), each with core content, '
          'a described diagram, a worked example, a scenario, checks for understanding, key terms and primary sources.',
          f'- **{len(CERT_ITEMS)} bank items**: ' + ', '.join(f"{n} {t}" for t, n in sorted(_count(CERT_ITEMS).items())) +
          '. Single-answer keys are balanced across positions; option lengths were rebalanced so the key is not usually the longest.',
          f'- **{len(GLOSSARY)} key terms** in the supplements; those not already defined are added to the course glossary (marked ‡).', '',
          '| Section | Lesson | Exam objectives | Sources |', '|---|---|---|---|']
    for s in SUPPLEMENTS:
        L.append(f"| {s['title']} | {s['course']} {s['chapter']}.{s['lesson']} | {', '.join(label(c) for c in sorted(s['cert'], key=sort_key))} | "
                 f"{'; '.join(SOURCES[x] for x in s['sources'])} |")
    L += _round2(objs, a['summary'])
    L += ['', '## Remaining gaps and partials', '',
          'No exam objective is a gap. Every objective that is not yet *covered* is listed with the reason and the checklist terms '
          'the linked lessons still do not mention. Objectives are in exam order; the assumed weight is the share of that exam.', '']
    for k, e in EXAMS.items():
        rows = [(oid, v) for oid, v in objs.items() if oid.startswith(k + ':') and v['status'] != 'covered']
        L += [f"### {e['name']} {e['code']} — {len(rows)} not yet covered", '']
        if not rows:
            L += ['None.', '']
            continue
        L += ['| Objective | Weight (assumed) | Content (topic ratio) | Items | Lessons linked | Missing checklist terms |', '|---|---|---|---|---|---|']
        for oid, v in sorted(rows, key=lambda r: sort_key(r[0])):
            why = []
            L.append(f"| **{label(oid)}** {v['title'].rstrip('.')} | {v['weight']}% | {v['content']} ({v['content_ratio']}) | "
                     f"{len(v['items'])} ({v['assessment']}) | {', '.join(v['lessons'][:4]) or '—'} | {'; '.join(v['topics_missing']) or '—'} |")
        L.append('')
    L += ['## Covered objectives that still miss checklist terms', '',
          'Covered means ≥ 70% of the checklist is present; these objectives are covered but still miss the terms shown.', '']
    for k, e in EXAMS.items():
        rows = [(oid, v) for oid, v in objs.items() if oid.startswith(k + ':') and v['status'] == 'covered' and v['topics_missing']]
        if rows:
            L.append(f"- **{e['short']}**: " + '; '.join(f"{label(oid).split()[-1]} ({', '.join(v['topics_missing'][:6])}{'…' if len(v['topics_missing']) > 6 else ''})"
                                                         for oid, v in sorted(rows, key=lambda r: sort_key(r[0]))))
    L += ['', '## Sources cited by the pass-11 supplements', '']
    used = sorted({x for s in SUPPLEMENTS for x in s['sources']})
    L += [f'- `{x}`: {SOURCES[x]}' for x in used]
    L += ['', '## Limits', '',
          '- Coverage is estimated by keywords. A term being present does not prove it is taught to exam depth; SME review is still needed.',
          '- Practice exams report percent correct by domain. CompTIA reports scaled scores, so practice percentages do not convert to a pass or fail.',
          '- Items are CIWT-written, aligned to the objectives; none are CompTIA exam items.', '']
    return '\n'.join(L)


