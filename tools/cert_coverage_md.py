def _round2(objs, summary):
    from curriculum_v2.cert import misconceptions as MC
    counts = [len(v['items']) for v in objs.values()]
    short = sum(1 for n in counts if n < 8)
    o_objs, n_tags, n_mc = MC.coverage()
    L = ['', '## Round 2 (pass 11): partials closed, item depth, misconception tags, quality pass', '',
         '| Exam | Covered (before → after) | Partial | Weighted covered | Mapped items |', '|---|---|---|---|---|']
    for ex, (c, p, w, it) in _ROUND2_BEFORE.items():
        s = summary[ex]
        L.append(f"| {EXAMS[ex]['short']} | {c} → {s['covered']} of {s['total']} | {p} → {s['partial']} | {w}% → {s['weighted_covered']}% | {it} → {s['items']} |")
    L += ['', f'- Objectives with fewer than 8 mapped items: {_ROUND2_BEFORE_SHORT} → {short}; fewest items on any objective: '
              f'{_ROUND2_BEFORE_MIN} → {min(counts)}. High-weight objectives (A+ Core 1 domains 1 and 5, Core 2 domain 3, Network+ 2.4, 4.1, 4.2, 5.4) '
              'were taken to at least 10.',
          f'- Misconception tags: {n_mc} misconceptions and {n_tags} tagged wrong options across {len(o_objs)} CIWT objectives, in the schema of '
          'the adaptive engine on `refinement` (`curriculum_v2/misconceptions.py`: MISCONCEPTIONS[id] = obj/label/fix/terms; '
          'TAGS[(bank_id, distractor)] = id). Ids use the `MC-C-` prefix. See `curriculum_v2/cert/misconceptions.py` for the merge hook.',
          f'- Quality pass: 40 sampled items reviewed; {QUALITY_CHECKED_OK} needed no change. Fixes, including ones found while re-reading round-2 items outside the sample:', '']
    L += [f'  - `{b}`: {t}' for b, t in QUALITY_FIXES]
    return L + ['']


def _count(items):
    out = {}
    for q in items:
        out[q['type']] = out.get(q['type'], 0) + 1
    return out


if __name__ == '__main__':
    text = build()
    path = os.path.join(ROOT, 'CERT_COVERAGE.md')
    if '--check' in sys.argv:
        cur = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
        print('CERT_COVERAGE.md is', 'current' if cur == text else 'STALE')
        sys.exit(0 if cur == text else 1)
    open(path, 'w', encoding='utf-8').write(text)
    print('wrote', path, len(text), 'chars')
