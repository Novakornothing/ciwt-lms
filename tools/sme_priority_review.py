"""Prioritised SME review checklist (Pending SME review). Read-only: scans the item pools and the explanation ladders.
Usage: python tools/sme_priority_review.py [OUT.md]   (default docs/SME_PRIORITY_REVIEW.md)"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from curriculum_readiness import original_pools  # noqa: E402
from curriculum_v2 import ladder as LD  # noqa: E402
from curriculum_v2.cert.items import CERT_ITEMS  # noqa: E402

GEN_SECTIONS = ('incident-application', 'standard-of-work', 'practice-standard-for-this-lesson', 'beyond-the-quiz',
                'the-scenario', 'your-turn-scaffolded-checklist', 'scaffolded-checklist', 'common-beginner-mistakes',
                'check-your-understanding')
COURSES = ('ITSUP', 'NETOPS', 'CLIENT')
# Text guards for the two items that were disputed in spot-checks; an item counts as still disputed if a guard fails.
DISPUTE_GUARDS = {'Q9.11': lambda q: 'samba' not in q['correct'].lower(),
                  'X-IT-11.3.3': lambda q: not any('documented vendor fix' in o.lower() for o in q['options'])}
CITES = re.compile(r'RFC|IEEE|NIST|Microsoft|CompTIA|Cisco|IETF|JEDEC|ISO|vendor|Apple|Linux man|Red Hat|Ubuntu', re.I)


def where(text):
    """file:line of the first 50 characters of a stem/question (git grep, fixed string)."""
    needle = text[:50]
    r = subprocess.run(['git', 'grep', '-n', '-F', needle, '--', 'curriculum_v2', '*.py'], cwd=ROOT, capture_output=True, text=True)
    hit = next((ln for ln in r.stdout.splitlines() if 'tests/' not in ln), '')
    return ':'.join(hit.split(':')[:2]) if hit else '(not found by text search)'


def item(pools, bid):
    return next((q for p in pools.values() for q in p if q.get('bank_id') == bid), None)


def ratio(q):
    others = [len(o) for o in q['options'] if o != q['correct']]
    return len(q['correct']) / max(others) if others else 0


def main(out):
    pools = original_pools()
    L = []
    w = L.append
    w('# SME priority review — highest risk first\n')
    w('Generated by `tools/sme_priority_review.py` (read-only scan of the current content). '
      'All listed items are **Pending SME review**.\n')
    disputed = [bid for bid, ok in DISPUTE_GUARDS.items() if not (item(pools, bid) and ok(item(pools, bid)))]
    w(f'## Priority 1: disputed or ambiguous items — {len(disputed)} disputed\n')
    w(f'- **Disputed items: {len(disputed)}.** ' + ('Still disputed: ' + ', '.join(disputed) + '.' if disputed else
      'Both previously disputed items (Q9.11, X-IT-11.3.3) were rewritten in content round 7 and pass their text guards; '
      'they are listed below only so the SME can confirm the rewrite.') + '\n')
    why = {'Q9.11': 'Was disputed (spot-check round 4: Samba `case sensitive = auto` lists both names). **Round 7:** re-asked about the '
                    'file systems themselves (ext4 case-sensitive, Windows folders case-insensitive by default); no Samba-dependent key.',
           'X-IT-11.3.3': 'Had a second defensible option (spot-check round 5: "known, documented vendor fix"). **Round 7:** that '
                          'distractor replaced; every remaining distractor makes a rebuild easier, so only "no tested backup" is defensible.'}
    for bid in ('Q9.11', 'X-IT-11.3.3'):
        q = item(pools, bid)
        if not q:
            w(f'- **{bid}**: not found in the pools (check the id).\n')
            continue
        w(f'### {bid} — `{where(q.get("text") or q.get("question") or "")}`\n')
        w(f'- **Stem:** {q.get("text") or q.get("question")}')
        for o in q['options']:
            w(f'  - {"**[key]** " if o == q["correct"] else ""}{o}')
        w(f'- **Why flagged:** {why[bid]}\n')
    w('## Priority 2: key noticeably longer than the distractors\n')
    w('A key at least 15% longer than the longest distractor (a test-wise cue). Every original pool (chapter checks, question '
      'bank A1–N3, exam supplement, ITSUP expansion), then every ladder quick check.\n')
    chk = [q for name, p in pools.items() for q in p
           if (q.get('type') or 'single') == 'single' and q.get('correct') in (q.get('options') or [])]
    flagged = sorted((q for q in chk if ratio(q) >= 1.15), key=ratio, reverse=True)
    if flagged:
        w('| Item | Key/longest distractor | File | Key |\n|---|---|---|---|')
        for q in flagged:
            w(f'| {q.get("bank_id")} | {ratio(q):.2f}× | `{where(q.get("text") or "")}` | {q["correct"]} |')
    else:
        w(f'- **Item pools: 0 flagged** across {len(pools)} pools / {len(chk)} single-answer items (Option B pass 3 lengthened '
          'one distractor on the 106 question-bank and supplement items that were over the line).')
    lc = []
    for (course, label, sid), raw in LD.ladder().items():
        if raw.get('type') != 'section':
            continue
        ent = LD.entry(course, label, sid)
        for rung in ('R0', 'R1', 'R2', 'R3', 'R4'):
            for c in LD.rung_checks(ent, rung) or []:
                if c.get('correct') in (c.get('options') or []) and ratio(c) >= 1.15:
                    lc.append((ratio(c), course, label, sid, c))
    lc.sort(key=lambda x: -x[0])
    if lc:
        w(f'\nLadder quick checks (not graded) with a key ≥ 1.15× the longest distractor: {len(lc)} in total. Top 15:\n')
        w('| Check id | Ratio | Section | Key |\n|---|---|---|---|')
        for r, course, label, sid, c in lc[:15]:
            w(f'| `{c["id"]}` | {r:.2f}× | {course} {label} `{sid}` | {c["correct"]} |')
    else:
        nl = sum(len(LD.rung_checks(LD.entry(*k), r) or []) for k, v in LD.ladder().items() if v.get('type') == 'section'
                 for r in ('R0', 'R1', 'R2', 'R3', 'R4'))
        w(f'- **Ladder quick checks (key ≥ 1.15× longest distractor): 0 flagged** across {nl} checks.')
    w('\n## Priority 3: templated NETOPS practice/capstone ladders and SAME_AS reuse\n')
    lad = LD.ladder()
    bespoke_note = 'Option B pass 3'
    practice = sorted(k for k, v in lad.items() if k[0] == 'NETOPS' and k[2] in GEN_SECTIONS and v.get('type') == 'section')
    gen = [k for k in practice if not str(lad[k].get('note') or '').startswith(bespoke_note)]
    gen_file = os.path.exists(os.path.join(ROOT, 'curriculum_v2', 'ladder', 'netops', '_gen.py'))
    w(f'- **Templated NETOPS sections: {len(gen)}** of {len(practice)} practice/capstone sections '
      f'(incident application, standard of work, practice standard, beyond the quiz, scenario, checklist, mistakes, check). '
      + ('Every one now has its own hand-written ladder (Option B pass 3, `curriculum_v2/ladder/netops/_p3n1.py`–`_p3n6.py`); '
         if not gen else 'Still templated: ' + ', '.join(f'{k[1]} `{k[2]}`' for k in gen[:40]) + '. ')
      + ('the old template builder `_gen.py` is still present.' if gen_file else 'the old template builder `_gen.py` has been removed.'))
    same = sorted(k for k, v in lad.items() if v.get('type') == 'same_as' and k[0] in COURSES)
    per = {c: sum(1 for k in same if k[0] == c) for c in COURSES}
    total = {c: sum(1 for k, v in lad.items() if k[0] == c and v.get('type') == 'section') for c in COURSES}
    w(f'- **`same_as` reuse: {len(same)}** (' + ', '.join(f'{c} {per[c]}' for c in COURSES) + '). Bespoke laddered sections: '
      + ', '.join(f'{c} {total[c]}' for c in COURSES) + f', {sum(total.values())} in total.'
      + ('' if not same else ' Still reused: ' + ', '.join(f'{k[0]} {k[1]} `{k[2]}`' for k in same[:40])) + '\n')
    w('## Priority 4: cert items with no external source, misplaced and duplicate sections\n')
    thin = [i for i in CERT_ITEMS if str(i.get('obj', '')).startswith(('IT-7.', 'IT-12.')) and not CITES.search(i.get('explanation') or '')]
    w(f'- **{len(thin)} certification practice items on IT-7.x / IT-12.x cite only course practice** (no vendor document, RFC or standard '
      'in the explanation)' + (': ' + ', '.join(f'`{i["bank_id"]}`' for i in thin[:40]) + (' …' if len(thin) > 40 else '') if thin
                               else '. Round 7 added CompTIA / NIST / ITIL / RFC / PCI DSS sources (`curriculum_v2/cert/sources_round7.py`).'))
    keys = set(LD.ladder())
    if ('NETOPS', '1.2', 'memory-as-a-system-not-a-stick') not in keys and ('NETOPS', '1.2', 'client-addressing-in-the-real-world') not in keys:
        w('- **Misplaced and duplicate sections: resolved (round 7).** The RAM section "Memory as a system, not a stick" and the duplicate '
          '"Client addressing in the real world" were removed from NETOPS 1.2 (the 4.1 copy, objective NO-4.1, is kept).\n')
        L.append(''); open(out, 'w').write('\n'.join(L) + '\n')
        print(out, f'P1 disputed {len(disputed)}; P2 pools {len(flagged)}, ladder {len(lc)}; P3 gen {len(gen)}, same_as {len(same)}; P4 {len(thin)}')
        return
    w('- **Misplaced section:** NETOPS 1.2 `memory-as-a-system-not-a-stick` ("Memory as a system, not a stick") is RAM hardware '
      'content inside a networking lesson (`curriculum_v2/ladder/netops/ch01.py`). Move it to ITSUP or drop it from NETOPS.')
    w('- **Duplicate section:** "Client addressing in the real world" (`client-addressing-in-the-real-world`) appears in NETOPS 1.2 '
      'and again in NETOPS 4.1 (`curriculum_v2/ladder/netops/ch04.py`). Keep the 4.1 version (it matches objective NO-4.1).\n')
    open(out, 'w').write('\n'.join(L) + '\n')
    print(out, f'P1 disputed {len(disputed)}; P2 pools {len(flagged)}, ladder {len(lc)}; P3 gen {len(gen)}, same_as {len(same)}; P4 {len(thin)}')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'docs', 'SME_PRIORITY_REVIEW.md'))
